
-- RF011: registros de perdas e refugos na producao.
-- SQL compativel com PostgreSQL e H2.

CREATE TABLE registros_perda (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_producao_id  BIGINT NOT NULL,
    etapa              VARCHAR(120) NOT NULL,
    quantidade         NUMERIC(12,4) NOT NULL,
    unidade            VARCHAR(10) NOT NULL,
    motivo             VARCHAR(500) NOT NULL,
    registrado_por_id  BIGINT NOT NULL,
    registrado_em      TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_perda_ordem
        FOREIGN KEY (ordem_producao_id)
        REFERENCES ordens_producao (id),

    CONSTRAINT fk_perda_usuario
        FOREIGN KEY (registrado_por_id)
        REFERENCES usuarios (id),

    CONSTRAINT ck_perda_quantidade
        CHECK (quantidade > 0),

    CONSTRAINT ck_perda_unidade
        CHECK (unidade IN ('G', 'KG', 'ML', 'L', 'UN')),

    CONSTRAINT ck_perda_etapa
        CHECK (LENGTH(TRIM(etapa)) > 0),

    CONSTRAINT ck_perda_motivo
        CHECK (LENGTH(TRIM(motivo)) > 0)
);

-- RNF-D002: indices para consultas de perdas.
CREATE INDEX idx_perda_ordem
    ON registros_perda (ordem_producao_id);

CREATE INDEX idx_perda_registrado_em
    ON registros_perda (registrado_em);
