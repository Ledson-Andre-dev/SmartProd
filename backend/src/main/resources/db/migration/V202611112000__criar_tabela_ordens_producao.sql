-- RF008: ordens de producao.
-- SQL compativel com PostgreSQL e H2.

CREATE TABLE ordens_producao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantidade_unidades  INTEGER NOT NULL,
    horario_entrega      TIMESTAMP WITH TIME ZONE NOT NULL,
    status               VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    iniciada_em          TIMESTAMP WITH TIME ZONE,
    concluida_em         TIMESTAMP WITH TIME ZONE,
    quantidade_produzida INTEGER,
    responsavel_id       BIGINT NOT NULL,
    criado_por_id        BIGINT NOT NULL,

    CONSTRAINT fk_ordens_responsavel
        FOREIGN KEY (responsavel_id) REFERENCES usuarios (id),

    CONSTRAINT fk_ordens_criado_por
        FOREIGN KEY (criado_por_id) REFERENCES usuarios (id),

    CONSTRAINT ck_ordens_quantidade
        CHECK (quantidade_unidades > 0),

    CONSTRAINT ck_ordens_status
        CHECK (status IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDA')),

    CONSTRAINT ck_ordens_quantidade_produzida
        CHECK (quantidade_produzida IS NULL OR quantidade_produzida >= 0)
);

-- RNF-D002: indices para consultas do Kanban e filtros por data.
CREATE INDEX idx_ordens_status_entrega
    ON ordens_producao (status, horario_entrega);

CREATE INDEX idx_ordens_horario_entrega
    ON ordens_producao (horario_entrega);

CREATE INDEX idx_ordens_responsavel
    ON ordens_producao (responsavel_id);
